package com.ney.moonsalary.task;

/**
 * Источник игровых тиков плагина.
 * <p>
 * Тикает задачей с периодом в один тик, поэтому не зависит от
 * Paper-специфичного API и одинаково работает в тестах и на сервере.
 * На паузе (Vault выключен) счёт замирает вместе с окнами выплат.
 * <p>
 * Инкремент и чтение происходят только в основном потоке сервера
 * (задача планировщика, другие задачи, команды, события) -
 * поэтому обычный long, а не атомик.
 */
public class TickClock implements Runnable {

    private long ticks;

    @Override
    public void run() {
        ticks++;
    }

    /**
     * Текущий тик плагина.
     *
     * @return номер тика с момента активации
     */
    public long current() {
        return ticks;
    }

}
